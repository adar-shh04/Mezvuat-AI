"""Fail if an installed dependency's licence is unknown or incompatible with AGPL-3.0 (decision D7).

Run from backend/: `uv run --no-sync python ../scripts/check_licenses.py [--write ../docs/DEPENDENCY_LICENSES.md]`.
"""

from __future__ import annotations

import argparse
import importlib.metadata as metadata
import re
import sys
from pathlib import Path

COMPATIBLE = (
    "mit",
    "bsd",
    "apache",
    "isc",
    "psf",
    "python software foundation",
    "python-2.0",
    "mpl",
    "mozilla",
    "lgpl",
    "gnu lesser",
    "agpl",
    "gnu affero",
    "gpl-3",
    "gplv3",
    "unlicense",
    "public domain",
    "cc0",
    "zlib",
    "hpnd",
    "historical permission",
    "0bsd",
    "boost",
    "bsl-1.0",
    "unicode",
    "cnri",
    "zope public",
    "zpl",
)
INCOMPATIBLE = (
    "non-commercial",
    "noncommercial",
    "cc-by-nc",
    "proprietary",
    "sspl",
    "commons clause",
    "busl",
    "gpl-2.0-only",
    "gplv2 only",
)

# Packages whose metadata carries no licence field; verified by hand against the project's LICENSE file.
MANUAL: dict[str, str] = {
    "huey": "MIT (dist-info LICENSE)",
    "skops": "MIT (dist-info LICENSE)",
}


def license_of(distribution: metadata.Distribution) -> str:
    meta = distribution.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier", []) if c.startswith("License ::")]
    classifiers = [c for c in classifiers if c not in ("OSI Approved",)]
    if classifiers:
        return "; ".join(classifiers)
    raw = (meta.get("License") or "").strip()
    return raw.splitlines()[0][:120] if raw else ""


def verdict(name: str, license_text: str) -> str:
    text = (license_text or MANUAL.get(name, "")).lower()
    if not text:
        return "unknown"
    # An SPDX "A OR B" lets us choose, so one compatible alternative is enough.
    alternatives = re.split(r"\s+or\s+", text)
    if any(
        any(good in alt for good in COMPATIBLE) and not any(bad in alt for bad in INCOMPATIBLE) for alt in alternatives
    ):
        return "ok"
    if any(bad in text for bad in INCOMPATIBLE):
        return "incompatible"
    return "unknown"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", type=Path)
    args = parser.parse_args()
    rows: list[tuple[str, str, str, str]] = []
    for distribution in metadata.distributions():
        name = re.sub(r"[-_.]+", "-", distribution.metadata["Name"]).lower()
        if name == "mezvuat":
            continue
        text = license_of(distribution)
        rows.append((name, distribution.version, text or MANUAL.get(name, ""), verdict(name, text)))
    rows.sort()
    problems = [r for r in rows if r[3] != "ok"]
    if args.write:
        lines = [
            "# Dependency licences",
            "",
            "Generated by `scripts/check_licenses.py`. Do not edit by hand. Repository licence: AGPL-3.0.",
            "",
            "| Package | Version | Licence | Verdict |",
            "|---|---|---|---|",
            *[f"| {n} | {v} | {t.replace('|', '/')} | {s} |" for n, v, t, s in rows],
            "",
        ]
        args.write.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rows)} packages checked, {len(problems)} need attention")  # noqa: T201
    for name, version, text, status in problems:
        print(f"  {status}: {name} {version} [{text}]")  # noqa: T201
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
