// Fail if an installed npm package's licence is unknown or incompatible with AGPL-3.0 (decision D7).
// The frontend counterpart of scripts/check_licenses.py. Reads the licence each installed package declares.
// Usage (from frontend/): node scripts/check-licenses.mjs [--write ../docs/FRONTEND_DEPENDENCY_LICENSES.md]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const COMPATIBLE = new Set([
  "MIT",
  "MIT-0",
  "ISC",
  "0BSD",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "Apache-2.0",
  "BlueOak-1.0.0",
  "CC0-1.0",
  "CC-BY-3.0",
  "CC-BY-4.0",
  "Python-2.0",
  "MPL-2.0",
  "Unlicense",
  "Zlib",
  "LGPL-3.0-or-later",
  "LGPL-3.0-only",
  "AGPL-3.0-only",
  "AGPL-3.0-or-later",
  "GPL-3.0-only",
  "GPL-3.0-or-later",
]);

/** True when an SPDX expression (`A OR B`, `A AND B`, parentheses) can be satisfied by compatible licences. */
function compatible(expression) {
  const tokens = expression.replace(/[()]/g, " ").split(/\s+/).filter(Boolean);
  if (tokens.length === 1) return COMPATIBLE.has(tokens[0]);
  // A disjunction needs one compatible option; a conjunction needs all. Mixed expressions are rare: be strict.
  if (tokens.includes("OR") && !tokens.includes("AND")) return tokens.some((t) => t !== "OR" && COMPATIBLE.has(t));
  return tokens.filter((t) => t !== "AND" && t !== "OR").every((t) => COMPATIBLE.has(t));
}

function declaredLicense(manifest) {
  if (typeof manifest.license === "string") return manifest.license;
  if (manifest.license && typeof manifest.license.type === "string") return manifest.license.type;
  if (Array.isArray(manifest.licenses)) return manifest.licenses.map((l) => l.type ?? l).join(" OR ");
  return null;
}

const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const rows = [];
const problems = [];
for (const [path, entry] of Object.entries(lock.packages)) {
  if (!path) continue; // the project itself
  const manifestPath = join(path, "package.json");
  if (!existsSync(manifestPath)) continue; // an optional package for another platform
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const license = declaredLicense(manifest) ?? entry.license ?? null;
  const name = path.replace(/^.*node_modules\//, "");
  const ok = license !== null && compatible(license);
  rows.push({ name, version: manifest.version, license: license ?? "unknown", dev: Boolean(entry.dev), ok });
  if (!ok) problems.push(`${name}@${manifest.version}: ${license ?? "no licence declared"}`);
}
rows.sort((a, b) => a.name.localeCompare(b.name));

const writeAt = process.argv.indexOf("--write");
if (writeAt !== -1) {
  const target = process.argv[writeAt + 1];
  const lines = [
    "# Frontend dependency licences",
    "",
    "Generated by `frontend/scripts/check-licenses.mjs` from the packages installed on the machine that ran it",
    "(platform-specific optional packages differ between Windows and Linux). Do not edit by hand.",
    "Repository licence: AGPL-3.0.",
    "",
    "| Package | Version | Licence | Dev only | Verdict |",
    "|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.dev ? "yes" : "no"} | ${r.ok ? "ok" : "CHECK"} |`),
    "",
  ];
  writeFileSync(target, lines.join("\n"), "utf8");
  console.log(`wrote ${target}`);
}

const runtime = rows.filter((r) => !r.dev).length;
console.log(`${rows.length} installed packages (${runtime} runtime, ${rows.length - runtime} dev only)`);
if (problems.length > 0) {
  console.error(`Licences that are unknown or not known to be AGPL-3.0 compatible:\n  ${problems.join("\n  ")}`);
  process.exit(1);
}
console.log("all licences are compatible with AGPL-3.0");
