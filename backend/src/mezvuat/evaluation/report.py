"""Render retrieval results as Markdown from the JSON summaries the experiment runner writes.

Every figure comes from a run file, and each row names its MLflow run id. Nothing in the report is typed by hand.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

_METRICS = ("ndcg@10", "recall@10", "recall@100", "precision@10", "mrr@10")


def _format_run(row: dict[str, Any]) -> str:
    cells = [f"`{row['config']}`"]
    for metric in _METRICS:
        low, high = row["ci95"][metric]
        cells.append(f"{row['metrics'][metric]:.4f} ({low:.3f}, {high:.3f})")
    total = row["latency"].get("latency_total_p50_ms")
    p95 = row["latency"].get("latency_total_p95_ms")
    cells.append(f"{total:.1f} / {p95:.1f}" if total is not None else "n/a")
    cells.append(f"`{row['run_id'][:8]}`")
    return "| " + " | ".join(cells) + " |"


def _format_comparison(row: dict[str, Any]) -> str:
    return (
        f"| `{row['comparison']}` | {row['metric']} | {row['delta']:+.4f} | "
        f"({row['ci_low']:+.4f}, {row['ci_high']:+.4f}) | {row['permutation_p']:.4f} |"
    )


def render(summary_files: list[Path]) -> str:
    lines = [
        "# Retrieval results",
        "",
        "Generated by `mezvuat-exp report` from run summaries in `docs/eval/runs/`. Do not edit by hand.",
        "Values are means over queries with 95% percentile bootstrap intervals (10,000 resamples, resampling queries).",
        "Latency is on the development laptop, in milliseconds per query, p50 / p95, end to end through the pipeline.",
        "",
    ]
    for path in summary_files:
        rows: list[dict[str, Any]] = json.loads(path.read_text(encoding="utf-8"))
        runs = [row for row in rows if "config" in row]
        comparisons = [row for row in rows if "comparison" in row]
        if not runs:
            continue
        lines += [
            f"## {path.stem}",
            "",
            f"Dataset `{runs[0]['dataset']}`, split `{runs[0]['split']}`, {runs[0]['n_queries']} queries.",
            "",
            "| Config | " + " | ".join(_METRICS) + " | Latency p50 / p95 | MLflow run |",
            "|---|" + "---|" * (len(_METRICS) + 2),
            *[_format_run(row) for row in runs],
            "",
        ]
        if comparisons:
            lines += [
                "| Comparison | Metric | Delta | 95% CI | Randomisation p |",
                "|---|---|---|---|---|",
                *[_format_comparison(row) for row in comparisons],
                "",
            ]
    return "\n".join(lines)
